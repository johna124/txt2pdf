static unsigned short v17_glyph_width_1000(FontKind font, unsigned char c)
{
    if (font == FONT_COURIER)
        return 600;
    unsigned char b = v17_width_base_char(c);
    if (b >= 32 && b <= 126) {
        if (font == FONT_HELVETICA)
            return v17_helvetica_ascii[b - 32];
        else
            return v17_times_ascii[b - 32];
    }
    return 500;
}
static unsigned char v17_winansi_from_cp(int cp)
{
    if (cp >= 0x20 && cp <= 0x7E)
        return (unsigned char)cp;
    if (cp >= 0xA0 && cp <= 0xFF)
        return (unsigned char)cp;
    return '?';
}
static int v17_utf8_seq_len(unsigned char c)
{
    if (c < 0x80)
        return 1;
    if (c >= 0xC2 && c <= 0xDF)
        return 2;
    if (c >= 0xE0 && c <= 0xEF)
        return 3;
    if (c >= 0xF0 && c <= 0xF4)
        return 4;
    return 1;
}
static int v17_decode_utf8(const unsigned char *p,
                           size_t off,
                           size_t len,
                           int *cp,
                           size_t *consume)
{
    if (off >= len)
        return 0;
    unsigned char c = p[off];
    int need = v17_utf8_seq_len(c);
    if (need == 1) {
        *cp = c;
        *consume = 1;
        return 1;
    }
    if (off + (size_t)need > len)
        return 0;
    for (int k = 1; k < need; k++) {
        if ((p[off + (size_t)k] & 0xC0) != 0x80)
            return 0;
    }
    int v = 0;
    if (need == 2) {
        v = ((c & 0x1F) << 6) | (p[off + 1] & 0x3F);
    } else if (need == 3) {
        v = ((c & 0x0F) << 12) |
            ((p[off + 1] & 0x3F) << 6) |
            (p[off + 2] & 0x3F);
    } else {
        v = ((c & 0x07) << 18) |
            ((p[off + 1] & 0x3F) << 12) |
            ((p[off + 2] & 0x3F) << 6) |
            (p[off + 3] & 0x3F);
    }
    *cp = v;
    *consume = (size_t)need;
    return 1;
}
static void v17_advance_char(const char *s,
                             size_t off,
                             size_t slen,
                             unsigned char *out_c,
                             size_t *out_consume)
{
    const unsigned char *p = (const unsigned char *)s;
    if (g_is_utf8 && p[off] >= 0x80) {
        int cp = 0;
        size_t cons = 1;
        if (v17_decode_utf8(p, off, slen, &cp, &cons)) {
            *out_c = v17_winansi_from_cp(cp);
            *out_consume = cons;
            return;
        }
    }
    unsigned char c = p[off];
    if (c == '\t')
        c = ' ';
    *out_c = c;
    *out_consume = 1;
}
static double v17_text_width_pt(const char *s,
                                FontKind font,
                                double font_size,
                                int trim_trailing)
{
    size_t len = strlen(s);
    size_t off = 0;
    double total = 0.0;
    double non_space_total = 0.0;
    while (off < len) {
        unsigned char c = 0;
        size_t cons = 1;
        v17_advance_char(s, off, len, &c, &cons);
        double cw = font_size *
                    (double)v17_glyph_width_1000(font, c) /
                    1000.0;
        total += cw;
        if (!v17_is_space_char(c))
            non_space_total = total;
        off += cons;
    }
    return trim_trailing ? non_space_total : total;
}
static void v17_next_visual_chunk(const char *s,
                                  size_t off,
                                  size_t slen,
                                  double max_width,
                                  FontKind font,
                                  char **out_text,
                                  size_t *out_consume)
{
    double w = 0.0;
    size_t i = off;
    size_t last_space = 0;
    size_t last_punct = 0;
    while (i < slen) {
        unsigned char c = 0;
        size_t cons = 1;
        v17_advance_char(s, i, slen, &c, &cons);
        double cw = FONT_SIZE *
                    (double)v17_glyph_width_1000(font, c) /
                    1000.0;
        if (w + cw > max_width) {
            if (w == 0.0) {
                w += cw;
                i += cons;
            }
            break;
        }
        w += cw;
        i += cons;
        if (v17_is_space_char(c))
            last_space = i;
        else if (c == '-' || c == '/')
            last_punct = i;
    }
    if (i >= slen) {
        *out_text = xstrndup(s + off, slen - off);
        *out_consume = slen - off;
        return;
    }
    size_t break_i = 0;
    if (last_space > off)
        break_i = last_space;
    else if (last_punct > off)
        break_i = last_punct;
    else
        break_i = i;
    if (break_i <= off) {
        unsigned char c = 0;
        size_t cons = 1;
        v17_advance_char(s, off, slen, &c, &cons);
        break_i = off + cons;
    }
    if (break_i > slen)
        break_i = slen;
    *out_text = xstrndup(s + off, break_i - off);
    *out_consume = break_i - off;
}
static void v17_append_escaped_char(Str *out, unsigned char c)
{
    if (c == '\\')
        str_append_str(out, "\\\\");
    else if (c == '(')
        str_append_str(out, "\\(");
    else if (c == ')')
        str_append_str(out, "\\)");
    else if (c == '\r')
        str_append_str(out, "\\r");
    else if (c == '\n')
        str_append_str(out, "\\n");
    else if (c == '\t')
        str_append_char(out, ' ');
    else if (c >= 32)
        str_append_char(out, (char)c);
    else
        str_append_char(out, '?');
}
static void v17_pdf_escape(const char *s, Str *out)
{
    if (!out->data) {
        out->len = 0;
        out->cap = 0;
        str_init(out);
    } else {
        out->len = 0;
        if (out->cap > 0)
            out->data[0] = '\0';
    }
    const unsigned char *p = (const unsigned char *)s;
    size_t len = strlen(s);
    size_t i = 0;
    while (i < len) {
        if (g_is_utf8 && p[i] >= 0x80) {
            int cp = 0;
            size_t cons = 1;
            if (v17_decode_utf8(p, i, len, &cp, &cons)) {
                unsigned char w = v17_winansi_from_cp(cp);
                v17_append_escaped_char(out, w);
                i += cons;
                continue;
            }
        }
        v17_append_escaped_char(out, p[i]);
        i++;
    }
}
