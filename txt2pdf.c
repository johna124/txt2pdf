        cjk_write_fontfile(out, offsets, cjk_file_obj, ff, fl);
        cjk_write_descriptor(out, offsets, cjk_desc_obj, cjk_file_obj);
        cjk_write_cidfont(out, offsets, cjk_cid_obj, cjk_desc_obj, used, nused);
