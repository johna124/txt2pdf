/* PDF 1.5 native object streams + cross-reference streams.
   No external qpdf dependency. */

static int g_pdf_minor = 5;        /* default: PDF 1.5 */
static int g_objstm_generate = 1;  /* default: --object-streams=generate */

typedef struct {
    int obj;
    Str body;
} Pdf15Obj;

typedef struct {
    Pdf15Obj *v;
    size_t n;
    size_t cap;
} Pdf15ObjStm;

static void pdf15_objstm_init(Pdf15ObjStm *os)
{
    os->v = NULL;
    os->n = 0;
    os->cap = 0;
}

static void *pdf15_xcalloc(size_t n, size_t sz)
{
    size_t bytes = n * sz;
    void *p = xmalloc(bytes ? bytes : 1);
    memset(p, 0, bytes ? bytes : 1);
    return p;
}

static char *pdf15_vformat(const char *fmt, va_list ap)
{
    va_list cp;
    va_copy(cp, ap);
    int n = vsnprintf(NULL, 0, fmt, cp);
    va_end(cp);

    if (n < 0)
        return xstrdup("");

    char *buf = xmalloc((size_t)n + 1);
    vsnprintf(buf, (size_t)n + 1, fmt, ap);
    return buf;
}

static void pdf15_objstm_add_body(Pdf15ObjStm *os, int obj, const char *body)
{
    if (os->n == os->cap) {
        os->cap = os->cap ? os->cap * 2 : 64;
        os->v = xrealloc(os->v, os->cap * sizeof(Pdf15Obj));
    }

    os->v[os->n].obj = obj;
    str_init(&os->v[os->n].body);
    str_append_str(&os->v[os->n].body, body ? body : "");
    os->n++;
}


/* Emit a non-stream object.
   In PDF 1.5 object-stream mode it is buffered.
   In classic mode it is written as usual. */
static void pdf15_emit_dict(FILE *out,
                            long *offsets,
                            Pdf15ObjStm *os,
                            int obj,
                            const char *fmt,
                            ...)
{
    va_list ap;

    if (g_objstm_generate) {
        va_start(ap, fmt);
        char *body = pdf15_vformat(fmt, ap);
        va_end(ap);

        pdf15_objstm_add_body(os, obj, body);
        free(body);
        return;
    }

    offsets[obj] = ftell(out);
    fprintf(out, "%d 0 obj\n", obj);

    va_start(ap, fmt);
    vfprintf(out, fmt, ap);
    va_end(ap);

    fprintf(out, "\nendobj\n");
}

static int pdf15_obj_cmp(const void *a, const void *b)
{
    const Pdf15Obj *oa = (const Pdf15Obj *)a;
    const Pdf15Obj *ob = (const Pdf15Obj *)b;
    return (oa->obj > ob->obj) - (oa->obj < ob->obj);
}

static void pdf15_put_be16(unsigned char *p, uint16_t v)
{
    p[0] = (unsigned char)((v >> 8) & 255);
    p[1] = (unsigned char)(v & 255);
}

static void pdf15_put_be32(unsigned char *p, uint32_t v)
{
    p[0] = (unsigned char)((v >> 24) & 255);
    p[1] = (unsigned char)((v >> 16) & 255);
    p[2] = (unsigned char)((v >> 8) & 255);
    p[3] = (unsigned char)(v & 255);
}

/* Write /ObjStm.
   Offsets in the object-stream header are relative to /First,
   i.e. relative to the first object body. */
static void pdf15_write_objstm(FILE *out,
                               long *offsets,
                               int objstm_obj,
                               Pdf15ObjStm *os,
                               int *obj_parent,
                               int *obj_index)
{
    if (os->n == 0)
        return;

    qsort(os->v, os->n, sizeof(Pdf15Obj), pdf15_obj_cmp);

    Str header;
    Str bodies;
    Str raw;

    str_init(&header);
    str_init(&bodies);
    str_init(&raw);

    for (size_t i = 0; i < os->n; i++) {
        int obj = os->v[i].obj;

        str_appendf(&header, "%d %zu ", obj, bodies.len);

        obj_parent[obj] = objstm_obj;
        obj_index[obj] = (int)i;

        str_append(&bodies, os->v[i].body.data, os->v[i].body.len);
        str_append_char(&bodies, '\n');
    }

    size_t first = header.len;

    str_append(&raw, header.data, header.len);
    str_append(&raw, bodies.data, bodies.len);

    char extra[160];
    snprintf(extra, sizeof(extra),
             " /Type /ObjStm /N %zu /First %zu",
             os->n, first);

    write_pdf_stream_obj(out, offsets, objstm_obj,
                         extra, raw.data ? raw.data : "", raw.len);

    for (size_t i = 0; i < os->n; i++)
        str_free(&os->v[i].body);

    free(os->v);
    os->v = NULL;
    os->n = 0;
    os->cap = 0;

    str_free(&header);
    str_free(&bodies);
    str_free(&raw);
}

/* Write /XRef stream using /W [1 4 2].
   Entry size: 7 bytes.
   type 0: free
   type 1: normal object, field2 = file offset
   type 2: compressed object, field2 = ObjStm object, field3 = index inside ObjStm */
static void pdf15_write_xref_stream(FILE *out,
                                    long *offsets,
                                    int xref_obj,
                                    int total_objs,
                                    int root_obj,
                                    const int *obj_parent,
                                    const int *obj_index)
{
    size_t raw_len = (size_t)(total_objs + 1) * 7;
    unsigned char *raw = xmalloc(raw_len ? raw_len : 1);
    memset(raw, 0, raw_len);

    /* Object 0: head of free list, generation 65535 */
    raw[0] = 0;
    pdf15_put_be32(raw + 1, 0);
    pdf15_put_be16(raw + 5, 65535);

    long xref_pos = ftell(out);

    for (int obj = 1; obj <= total_objs; obj++) {
        unsigned char *e = raw + (size_t)obj * 7;

        if (obj == xref_obj) {
            e[0] = 1;
            pdf15_put_be32(e + 1, (uint32_t)xref_pos);
            pdf15_put_be16(e + 5, 0);
        } else if (obj_parent && obj_parent[obj] > 0) {
            e[0] = 2;
            pdf15_put_be32(e + 1, (uint32_t)obj_parent[obj]);
            pdf15_put_be16(e + 5, (uint16_t)obj_index[obj]);
        } else {
            e[0] = 1;
            pdf15_put_be32(e + 1, (uint32_t)offsets[obj]);
            pdf15_put_be16(e + 5, 0);
        }
    }

    char extra[220];
    snprintf(extra, sizeof(extra),
             " /Type /XRef /Size %d /Root %d 0 R /W [1 4 2] /Index [0 %d]",
             total_objs + 1, root_obj, total_objs + 1);

    write_pdf_stream_obj(out, offsets, xref_obj,
                         extra, raw, raw_len);

    fprintf(out, "startxref\n%ld\n%%%%EOF\n", xref_pos);

    free(raw);
}
